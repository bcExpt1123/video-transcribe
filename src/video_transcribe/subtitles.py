"""Subtitle file formats (SRT, ASS, WebVTT) and YAML style -> ASS style."""

from __future__ import annotations

import re
from pathlib import Path

from .data import Cue

# --------------------------------------------------------------------- time formats


def _split_ms(t: float) -> tuple[int, int, int, int]:
    ms = max(0, int(round(t * 1000)))
    h, ms = divmod(ms, 3_600_000)
    m, ms = divmod(ms, 60_000)
    s, ms = divmod(ms, 1000)
    return h, m, s, ms


def srt_time(t: float) -> str:
    h, m, s, ms = _split_ms(t)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def vtt_time(t: float) -> str:
    h, m, s, ms = _split_ms(t)
    return f"{h:02d}:{m:02d}:{s:02d}.{ms:03d}"


def ass_time(t: float) -> str:
    cs = max(0, int(round(t * 100)))  # ASS has centisecond precision; round, don't truncate
    h, cs = divmod(cs, 360_000)
    m, cs = divmod(cs, 6000)
    s, cs = divmod(cs, 100)
    return f"{h:d}:{m:02d}:{s:02d}.{cs:02d}"


def _quantize(cues: list[Cue], unit: float) -> list[tuple[float, float, Cue]]:
    """Round times to the format's unit while keeping order and no overlap."""
    out = []
    prev_end = 0.0
    for c in cues:
        s = round(c.start / unit) * unit
        e = round(c.end / unit) * unit
        s = max(s, prev_end)
        if e <= s:
            e = s + unit
        out.append((s, e, c))
        prev_end = e
    return out


# --------------------------------------------------------------------- writers


def to_srt(cues: list[Cue]) -> str:
    blocks = []
    for i, (s, e, c) in enumerate(_quantize(cues, 0.001), 1):
        blocks.append(f"{i}\n{srt_time(s)} --> {srt_time(e)}\n{c.text}\n")
    return "\n".join(blocks)


def to_vtt(cues: list[Cue]) -> str:
    blocks = ["WEBVTT\n"]
    for s, e, c in _quantize(cues, 0.001):
        text = c.text.replace("-->", "->")
        blocks.append(f"{vtt_time(s)} --> {vtt_time(e)}\n{text}\n")
    return "\n".join(blocks)


_ALIGN = {
    "bottom-left": 1, "bottom-center": 2, "bottom-right": 3,
    "middle-left": 4, "middle-center": 5, "middle-right": 6,
    "top-left": 7, "top-center": 8, "top-right": 9,
}


def ass_color(value: str) -> str:
    """'#RRGGBB' / '#AARRGGBB' (AA = opacity) -> ASS '&HAABBGGRR' (AA = transparency)."""
    v = value.lstrip("#")
    if len(v) == 6:
        a, rgb = 255, v
    else:
        a, rgb = int(v[:2], 16), v[2:]
    r, g, b = rgb[0:2], rgb[2:4], rgb[4:6]
    return f"&H{255 - a:02X}{b}{g}{r}".upper()


def ass_style_line(style: dict, height: int) -> str:
    k = height / 1080.0
    box = style["border_style"] == "box"

    def px(name):
        return f"{float(style[name]) * k:.2f}".rstrip("0").rstrip(".")

    fields = [
        "Default",
        style["font_name"],
        px("font_size"),
        ass_color(style["primary_color"]),
        ass_color(style["primary_color"]),
        # libass draws the opaque box (BorderStyle 3) in OutlineColour.
        ass_color(style["back_color"] if box else style["outline_color"]),
        ass_color(style["back_color"]),
        "-1" if style["bold"] else "0",
        "-1" if style["italic"] else "0",
        "0", "0", "100", "100",
        px("spacing"),
        "0",
        "3" if box else "1",
        px("outline"),
        px("shadow"),
        str(_ALIGN[style["position"]]),
        str(round(float(style["margin_l"]) * k)),
        str(round(float(style["margin_r"]) * k)),
        str(round(float(style["margin_v"]) * k)),
        "1",
    ]
    return "Style: " + ",".join(fields)


def _ass_escape(text: str) -> str:
    text = text.replace("\\", "＼").replace("{", "｛").replace("}", "｝")
    return text.replace("\n", "\\N")


def to_ass(cues: list[Cue], style: dict, width: int, height: int) -> str:
    head = [
        "[Script Info]",
        "; Generated by video-transcribe",
        "ScriptType: v4.00+",
        f"PlayResX: {width}",
        f"PlayResY: {height}",
        "WrapStyle: 0",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: None",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, "
        "BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, "
        "BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
        ass_style_line(style, height),
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ]
    events = [
        f"Dialogue: 0,{ass_time(s)},{ass_time(e)},Default,,0,0,0,,{_ass_escape(c.text)}"
        for s, e, c in _quantize(cues, 0.01)
    ]
    return "\n".join(head + events) + "\n"


def write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    # utf-8 with BOM for SRT helps some Windows players detect Chinese correctly.
    encoding = "utf-8-sig" if path.suffix.lower() == ".srt" else "utf-8"
    path.write_text(text, encoding=encoding, newline="\n")
    return path


# --------------------------------------------------------------------- readers

_TIME_RE = re.compile(
    r"(?:(\d+):)?(\d{1,2}):(\d{2})[,.](\d{1,3})\s*-->\s*(?:(\d+):)?(\d{1,2}):(\d{2})[,.](\d{1,3})"
)


def _t(h, m, s, frac) -> float:
    return int(h or 0) * 3600 + int(m) * 60 + int(s) + int(frac.ljust(3, "0")) / 1000


def parse_srt_or_vtt(text: str) -> list[Cue]:
    """Parse SRT or WebVTT text (styling tags are stripped)."""
    text = text.lstrip("﻿").replace("\r\n", "\n")
    cues = []
    for block in re.split(r"\n\s*\n", text):
        lines = block.strip("\n").split("\n")
        for i, line in enumerate(lines):
            m = _TIME_RE.search(line)
            if m:
                g = m.groups()
                body = [re.sub(r"<[^>]+>", "", x) for x in lines[i + 1 :] if x.strip()]
                if body:
                    cues.append(Cue(start=_t(*g[:4]), end=_t(*g[4:]), lines=body))
                break
    cues.sort(key=lambda c: c.start)
    return cues


def read_cues(path: Path) -> list[Cue]:
    return parse_srt_or_vtt(path.read_text(encoding="utf-8-sig", errors="replace"))
